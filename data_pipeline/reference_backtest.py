def load_weather(year: int = 2016) -> pd.DataFrame:
    path = RAW / "open_meteo" / "2026-08-09" / f"konstanz_{year}_weather.json"
    payload = json.loads(path.read_text(encoding="utf-8"))
    hourly = payload["hourly"]
    frame = pd.DataFrame(
        {
            "temperature_c": hourly["temperature_2m"],
            "shortwave_wm2": hourly["shortwave_radiation"],
            "direct_wm2": hourly["direct_radiation"],
            "diffuse_wm2": hourly["diffuse_radiation"],
        },
        index=pd.to_datetime(hourly["time"], utc=True),
    )
    frame.index.name = "timestamp"
    expected = pd.date_range(f"{year}-01-01", f"{year}-12-31T23:45:00", freq="15min", tz="UTC")
    return frame.reindex(expected).interpolate(limit_direction="both")


def solar_elevation_deg(index: pd.DatetimeIndex, lat: float = KONSTANZ_LAT, lon: float = KONSTANZ_LON) -> np.ndarray:
    """Approximate solar elevation (degrees) from UTC time and coordinates.
    Standard declination + hour-angle formula; ignores the equation of time
    (a few minutes of error), adequate for a feature-engineering input."""
    day_of_year = index.dayofyear.values
    utc_hour = index.hour.values + index.minute.values / 60
    declination = np.radians(23.45 * np.sin(np.radians(360 / 365 * (284 + day_of_year))))
    solar_time = utc_hour + lon / 15
    hour_angle = np.radians(15 * (solar_time - 12))
    lat_r = np.radians(lat)
    elevation = np.arcsin(
        np.sin(declination) * np.sin(lat_r) + np.cos(declination) * np.cos(lat_r) * np.cos(hour_angle)
    )
    return np.degrees(elevation)


def build_calendar_features(index: pd.DatetimeIndex) -> pd.DataFrame:
    return pd.DataFrame(
        {
            "hour": index.hour,
            "dayofweek": index.dayofweek,
            "month": index.month,
            "is_weekend": (index.dayofweek >= 5).astype(int),
            "solar_elevation_deg": solar_elevation_deg(index),
        },
        index=index,
    )


def add_lag_and_rolling(series: pd.Series, lags: tuple[int, ...] = (4, 8, 96, 192)) -> pd.DataFrame:
    """Lags in units of 15-min intervals: 4=1h, 8=2h, 96=24h, 192=48h."""
    frame = pd.DataFrame(index=series.index)
    for lag in lags:
        frame[f"lag_{lag}"] = series.shift(lag)
    frame["roll_mean_96"] = series.shift(1).rolling(96, min_periods=48).mean()
    frame["roll_std_96"] = series.shift(1).rolling(96, min_periods=48).std()
    return frame


