#!/usr/bin/env python3
"""Reference backtest: real public data -> Evidergy core algorithms -> versioned metrics.

Purpose
-------
The 2026-08-08 business plan states plainly that public-dataset backtesting was not
yet complete and no accuracy had been verified. This script closes that specific gap
using data that is public, free, checksummed and reproducible *today*, without
waiting on the written commercial-use permission that DKASC/DKP (sources.json,
tier A, "written_permission_required_before_commercial_training_or_redistribution")
still requires. It is deliberately NOT presented as the Alice Springs pilot: it is a
representative public reference dataset used to demonstrate that the algorithms in
core_models.py behave correctly, are bounded/calibrated, and can be backtested
end-to-end on real (non-synthetic) meter data. That is the literal TRL4 bar in the
PERIscope guidelines: "proof of concept has been validated. Demonstration of
technical feasibility have been shown with representative data."

Data sources (see docs/REFERENCE_DATASET.md for full provenance and licence text)
-----------------------------------------------------------------------------------
1. Open Power System Data - household_data, release 2020-04-15 (CC-BY, ISC Konstanz).
   Real 15-minute cumulative smart-meter readings, 2014-12 to 2019-05.
     - DE_KN_residential4: grid_import, grid_export, pv, plus five submetered
       appliance circuits (dishwasher, freezer, heat_pump, refrigerator,
       washing_machine, ev). ~100% interval coverage in calendar year 2016.
     - DE_KN_industrial2: grid_import, pv, storage_charge, storage_decharge
       (a real behind-the-meter battery). ~68-86% coverage in 2016 -- these are
       genuine gaps in the source file, not injected for the demo.
2. Open-Meteo Historical Weather API (open data, no key required). Hourly
   temperature_2m and shortwave/direct/diffuse radiation for Konstanz, Germany
   (47.6779N, 9.1732E), calendar year 2016.
3. DCCEEW National Greenhouse Accounts Factors 2025, Table 1: Northern Territory
   (Darwin-Katherine Interconnected System) location-based Scope 2 factor,
   0.56 kg CO2-e/kWh. Downloaded directly, no login, from dcceew.gov.au.

What is, and is not, being claimed
-----------------------------------
- Energy balance ("identity" check): grid_import - grid_export + pv is compared
  against itself by construction on residential4 (there is no independent,
  redundantly-metered PCC in this public dataset). This validates that the
  sign-convention / unit-conversion / residual code path reproduces the meter
  physics correctly on real, messy, DST-aware timestamps -- a legitimate TRL4-level
  pipeline check -- and is reported separately from "metering completeness"
  (how much of that identity load the five submeters actually explain), which is
  a genuine, non-circular, real-world statistic.
- Quantile load forecast: trained and backtested on a real target
  (grid_import - grid_export + pv) with a fixed, non-shuffled rolling-origin
  train/validate/test split, real calendar + weather features. Fully real,
  non-circular.
- PV evidence: the weather-adjusted baseline is fit on real irradiance/temperature
  and real PV output. Because this public release carries no labelled outage
  events (unlike the DKASC 2021 "Notes on the Data" the roadmap targets for the
  real pilot), detection recall/false-positive rate are measured by injecting
  synthetic, clearly-logged outage windows into real held-out PV output -- a
  standard fault-injection validation technique, not a claim of real labelled
  incidents.
- BESS evidence: OPSD publishes charge/discharge energy, not an OEM SOC signal.
  An indicative "charge-tracking index" is derived from real charge/discharge
  telemetry using a data-driven capacity estimate. The consistency-rule detection
  logic is then validated the same way as PV: synthetic sign/telemetry corruption
  injected into real intervals, recall and false-positive rate measured against
  clean real intervals.
- Scope 2: real monthly grid-import kWh (residential4, 2016) x the real,
  published NT (DKIS) location-based factor. 100% recompute consistency is the
  documented BP acceptance target for this check (deterministic multiplication),
  not a statistical claim.

Outputs
-------
data_processed/reference_2016/backtest_report.json   -- versioned metrics + provenance
data_processed/reference_2016/*.csv                  -- normalised extracts for audit
../lib/reference-dataset.ts (generated by generate_reference_ts.py, not this file)
"""
