def load_cumulative_meters(csv_path: Path, columns: dict[str, str], year: int) -> pd.DataFrame:
    """Load real cumulative-kWh meter columns, reindex to the full expected
    15-minute timeline, and convert to per-interval kW. Counter resets (a
    negative diff, which happens on real cumulative meters) are flagged and
    treated as missing rather than fabricated as negative power."""
    usecols = ["utc_timestamp", *columns.values()]
    frame = pd.read_csv(csv_path, usecols=usecols, parse_dates=["utc_timestamp"])
    frame = frame.rename(columns={v: k for k, v in columns.items()})
    frame = frame.set_index("utc_timestamp").sort_index()
    frame = frame[(frame.index.year == year)]
    expected = pd.date_range(f"{year}-01-01", f"{year}-12-31T23:45:00", freq="15min", tz="UTC")
    frame = frame.reindex(expected)
    frame.index.name = "timestamp"

    result = pd.DataFrame(index=frame.index)
    reset_count = 0
    for name in columns:
        cumulative = frame[name]
        delta_kwh = cumulative.diff()
        reset_mask = delta_kwh < 0
        reset_count += int(reset_mask.sum())
        delta_kwh = delta_kwh.mask(reset_mask)
        result[f"{name}_kw"] = delta_kwh / 0.25  # 15-minute interval -> kW
    result.attrs["meter_reset_count"] = reset_count
    return result


def build_residential4(year: int = 2016) -> pd.DataFrame:
    csv_path = RAW / "opsd_household" / "2020-04-15" / "household_data_15min_singleindex.csv"
    meters = load_cumulative_meters(csv_path, RESIDENTIAL_COLS, year)
    submeter_cols = [c for c in meters.columns if c.startswith("sub_")]
    df = pd.DataFrame(index=meters.index)
    # NaN propagates when either side is missing (no silent zero-fill of a missing
    # meter -- see the CN spec's "quality gate" principle: preserve gaps, flag them).
    df["grid_kw"] = meters["grid_import_kw"] - meters["grid_export_kw"]
    df["pv_kw"] = meters["pv_kw"]
    df["load_identity_kw"] = df["grid_kw"] + df["pv_kw"]  # whole-building consumption, by meter identity
    df["load_submetered_kw"] = meters[submeter_cols].sum(axis=1, min_count=1)
    df.attrs["meter_reset_count"] = meters.attrs["meter_reset_count"]
    df.attrs["raw_pv_missing"] = int(meters["pv_kw"].isna().sum())
    df.attrs["raw_grid_import_missing"] = int(meters["grid_import_kw"].isna().sum())
    return df


def build_industrial2(year: int = 2016) -> pd.DataFrame:
    csv_path = RAW / "opsd_household" / "2020-04-15" / "household_data_15min_singleindex.csv"
    meters = load_cumulative_meters(csv_path, INDUSTRIAL_COLS, year)
    df = pd.DataFrame(index=meters.index)
    df["grid_kw"] = meters["grid_import_kw"]
    df["pv_kw"] = meters["pv_kw"]
    # Real gaps must stay NaN (see build_residential4 note); a charge/discharge
    # reading of exactly 0 is a genuine "not cycling" observation, not a gap.
    df["bess_kw"] = meters["storage_decharge_kw"] - meters["storage_charge_kw"]
    df.attrs["meter_reset_count"] = meters.attrs["meter_reset_count"]
    df.attrs["raw_storage_missing"] = int(
        meters[["storage_charge_kw", "storage_decharge_kw"]].isna().all(axis=1).sum()
    )
    return df


