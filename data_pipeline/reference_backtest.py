def module_data_quality(industrial: pd.DataFrame) -> dict:
    # industrial.index is already the full expected 15-minute timeline for the year
    # (see load_cumulative_meters), and bess_kw carries real NaN gaps -- pass through
    # as-is so quality_flags measures the genuine source coverage.
    flags = quality_flags(industrial["bess_kw"], expected_frequency="15min")
